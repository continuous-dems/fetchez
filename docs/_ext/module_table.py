"""
module_table
~~~~~~~~~~~~~

Sphinx extension that generates an interactive HTML table of Fetchez modules
using the FetchezRegistry.

Usage in RST::

    .. module-table::

Usage in MyST Markdown::

    ```{module-table}
    ```
"""

from docutils import nodes
from sphinx.application import Sphinx
from sphinx.util.docutils import SphinxDirective

from fetchez.registry import ModuleRegistry


import inspect
from html import escape
from pathlib import Path


def generate_module_api_docs(app):
    """Generate autodoc pages for registered Fetchez modules."""

    ModuleRegistry.load_builtins()
    registry = ModuleRegistry.get_registry()

    output_dir = Path(app.srcdir) / "api" / "generated_modules"
    output_dir.mkdir(parents=True, exist_ok=True)

    pages = []

    canonical_classes = {}

    for name, _dict in sorted(registry.items()):
        if name in ["url_fetcher"]:
            continue

        cls = ModuleRegistry.get_class(name)
        if not inspect.isclass(cls):
            continue

        python_path = f"{cls.__module__}.{cls.__qualname__}"
        page = output_dir / f"{name}.rst"
        _title = f"{name} module"
        if python_path in canonical_classes:
            canonical_name = canonical_classes[python_path]

            # Generate a lightweight alias page instead of
            # documenting the same Python class twice.
            content = f"""\
{name}
{"=" * len(name)}

This registry name is an alias of :doc:`{canonical_name}`.
"""
        else:
            canonical_classes[python_path] = name

            content = f"""\
{name}
{"=" * len(name)}

.. autoclass:: {python_path}
   :members:
   :undoc-members:
   :special-members:
"""
        if not page.exists() or page.read_text() != content:
            page.write_text(content, encoding="utf-8")

        pages.append(name)

    # Remove stale autogenerated module pages.
    expected = {f"{name}.rst" for name in pages}
    expected.add("index.rst")

    for page in output_dir.glob("*.rst"):
        if page.name not in expected:
            page.unlink()

    # Generate the index automatically too.
    index = output_dir / "index.rst"

    toctree = "\n".join(f"   {name}" for name in pages)

    content = f"""\
Registered Module API
=====================

Automatically generated Python API references for registered Fetchez modules.

.. toctree::
   :maxdepth: 1

{toctree}
"""

    if not index.exists() or index.read_text() != content:
        index.write_text(content, encoding="utf-8")


def documentation_cell(directive, key, kind):
    """Return an HTML table cell linking to a Sphinx document."""

    if kind == "guide":
        docname = f"modules/{key}"
        label = "Guide"
    else:
        docname = f"api/generated_modules/{key}"
        label = "API"

    if docname not in directive.env.found_docs:
        return "<td>-</td>"

    href = directive.env.app.builder.get_relative_uri(
        directive.env.docname,
        docname,
    )

    return f'<td><a href="{escape(href, quote=True)}">{label}</a></td>'


class ModuleTableDirective(SphinxDirective):
    """Directive to generate an interactive module table using DataTables."""

    has_content = False
    required_arguments = 0
    optional_arguments = 0

    def run(self):
        ModuleRegistry.load_builtins()

        modules = ModuleRegistry.get_registry()

        rows = []
        for key in sorted(modules.keys()):
            meta = ModuleRegistry.get_info(key)

            _home_url = meta.get("urls", {}).get("home", "#")

            _env = self.env
            _docname = f"modules/{key}"

            guide_td = documentation_cell(self, key, "guide")
            api_td = documentation_cell(self, key, "api")

            rows.append(f"""
            <tr>
                <td><code>{key}</code></td>
                <td>{meta.get("category", "-")}</td>
                <td>{meta.get("desc", "-")}</td>
                {guide_td}
                {api_td}
            </tr>
            """)

        html = f"""
        <link rel="stylesheet" href="https://cdn.datatables.net/1.13.4/css/jquery.dataTables.min.css">

        <style>
            /* Overrides to make it fit Sphinx themes better */
            table.dataTable {{ font-size: 0.9em; }}
            .dataTables_wrapper {{ margin-top: 20px; }}
            code {{ background: #e3e3e3; padding: 2px 4px; border-radius: 3px; color: #333; }}
        </style>

        <div style="overflow-x: auto;">
            <table id="moduleTable" class="display" style="width:100%">
                <thead>
                    <tr>
                        <th>Module</th>
                        <th>Category</th>
                        <th>Description</th>
                        <th>Guide</th>
                        <th>API</th>
                    </tr>
                </thead>
                <tbody>
                    {"".join(rows)}
                </tbody>
            </table>
        </div>

        <script src="https://code.jquery.com/jquery-3.5.1.min.js"></script>
        <script src="https://cdn.datatables.net/1.13.4/js/jquery.dataTables.min.js"></script>

        <script>
            $(document).ready(function () {{
                $('#moduleTable').DataTable({{
                    "pageLength": 25,
                    "lengthMenu": [[10, 25, 50, -1], [10, 25, 50, "All"]],
                    "order": [[ 0, "asc" ]]
                }});
            }});
        </script>
        """

        raw_node = nodes.raw("", html, format="html")
        return [raw_node]


def setup(app: Sphinx):
    """Register the extension with Sphinx."""
    app.add_directive("module-table", ModuleTableDirective)
    app.connect("builder-inited", generate_module_api_docs)

    return {
        "version": "0.1.1",
        "parallel_read_safe": True,
        "parallel_write_safe": True,
    }
